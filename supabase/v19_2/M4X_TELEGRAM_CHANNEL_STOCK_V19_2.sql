-- 8) Secret cho worker được sinh tự động, lưu mã hóa trong Vault.
-- Edge Function chỉ lưu hash, nên người dùng không phải copy/paste secret.
do $$
declare
  v_secret text;
begin
  select decrypted_secret into v_secret
  from vault.decrypted_secrets
  where name='m4x_channel_worker_secret_v191'
  order by updated_at desc
  limit 1;

  if v_secret is null then
    v_secret := encode(gen_random_bytes(24),'hex');
    perform vault.create_secret(v_secret,'m4x_channel_worker_secret_v191','M4X Telegram Channel Worker V19.1');
  end if;

  update public.telegram_channel_settings
  set worker_secret_hash=encode(digest(v_secret,'sha256'),'hex'),updated_at=now()
  where id='main';
end $$;

