-- 7) LIVE STOCK: đồng bộ 1 tin tồn kho cố định + cảnh báo sắp hết/hết hàng
-- Số còn bán thực tế = stock_limit - sold_count - reserved_count.
create or replace function public.m4x_tg_stock_trigger()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_old integer;
  v_new integer;
  v_threshold integer := 5;
  v_id text;
  v_name text;
  v_stock_mode text;
  v_active boolean;
begin
  select coalesce(stock_low_threshold,5) into v_threshold
  from public.telegram_channel_settings where id='main';
  v_threshold := greatest(1,least(99,coalesce(v_threshold,5)));

  if tg_op='DELETE' then
    v_id := old.id::text;
    v_name := old.name;
    perform public.m4x_enqueue_channel_event(
      'stock_sync',
      'stock-sync:'||gen_random_uuid()::text,
      jsonb_build_object('product_id',v_id,'reason','delete')
    );
    return old;
  end if;

  v_id := new.id::text;
  v_name := new.name;
  v_stock_mode := coalesce(new.stock_mode,'unlimited');
  v_active := coalesce(new.active,false);

  -- Mọi thay đổi kho/tên/trạng thái đều làm mới tin tồn kho ghim.
  perform public.m4x_enqueue_channel_event(
    'stock_sync',
    'stock-sync:'||gen_random_uuid()::text,
    jsonb_build_object('product_id',v_id,'reason',lower(tg_op))
  );

  -- Chỉ cảnh báo khi sản phẩm hữu hạn đang bán và số ĐÃ BÁN/kho thật thay đổi.
  -- reserved_count vẫn cập nhật tin ghim nhưng không phát cảnh báo riêng để tránh spam do đơn chờ.
  if tg_op='UPDATE'
     and v_active is true
     and v_stock_mode='limited'
     and (old.sold_count is distinct from new.sold_count or old.stock_limit is distinct from new.stock_limit)
  then
    v_old := greatest(0,coalesce(old.stock_limit,0)-coalesce(old.sold_count,0)-coalesce(old.reserved_count,0));
    v_new := greatest(0,coalesce(new.stock_limit,0)-coalesce(new.sold_count,0)-coalesce(new.reserved_count,0));

    if v_new=0 and v_old>0 then
      perform public.m4x_enqueue_channel_event(
        'stock_alert',
        'stock-alert:'||v_id||':out:'||gen_random_uuid()::text,
        jsonb_build_object('product_id',new.id,'name',v_name,'available',v_new,'kind','out')
      );
    elsif v_new<=v_threshold and v_new>0 and v_old>v_threshold then
      perform public.m4x_enqueue_channel_event(
        'stock_alert',
        'stock-alert:'||v_id||':low:'||gen_random_uuid()::text,
        jsonb_build_object('product_id',new.id,'name',v_name,'available',v_new,'kind','low')
      );
    end if;
  end if;
  return new;
end;
$$;

