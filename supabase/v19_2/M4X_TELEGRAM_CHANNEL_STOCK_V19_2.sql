-- 3) Helper enqueue idempotent
create or replace function public.m4x_enqueue_channel_event(
  p_event_type text,
  p_dedupe_key text,
  p_payload jsonb default '{}'::jsonb,
  p_available_at timestamptz default now()
) returns bigint
language plpgsql
security definer
set search_path=public
as $$
declare v_id bigint;
begin
  insert into public.telegram_channel_queue(event_type,dedupe_key,payload,available_at)
  values(p_event_type,p_dedupe_key,coalesce(p_payload,'{}'::jsonb),coalesce(p_available_at,now()))
  on conflict(dedupe_key) do nothing
  returning id into v_id;
  return v_id;
end;
$$;
revoke all on function public.m4x_enqueue_channel_event(text,text,jsonb,timestamptz) from public,anon,authenticated;

-- 4) Sản phẩm mới: INSERT active hoặc lần đầu chuyển active=true
create or replace function public.m4x_tg_product_publish_trigger()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if (tg_op='INSERT' and new.active is true)
     or (tg_op='UPDATE' and new.active is true and coalesce(old.active,false) is false) then
    perform public.m4x_enqueue_channel_event(
      'new_product',
      'product:'||new.id::text||':published',
      jsonb_build_object(
        'id',new.id,
        'name',new.name,
        'description',new.description,
        'price',new.price,
        'old_price',new.old_price,
        'cover_url',new.cover_url,
        'created_at',new.created_at
      )
    );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_m4x_tg_product_publish on public.products;
create trigger trg_m4x_tg_product_publish
after insert or update of active on public.products
for each row execute function public.m4x_tg_product_publish_trigger();

-- 5) Hero/Flash Sale mới
create or replace function public.m4x_tg_hero_trigger()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if new.id='main' and new.enabled is true then
    if tg_op='INSERT' then
      perform public.m4x_enqueue_channel_event(
        'hero',
        'hero:'||to_char(coalesce(new.updated_at,now()),'YYYYMMDDHH24MISSMS'),
        to_jsonb(new)
      );
    elsif
      old.enabled is distinct from new.enabled or
      old.variant is distinct from new.variant or
      old.eyebrow is distinct from new.eyebrow or
      old.title is distinct from new.title or
      old.accent_text is distinct from new.accent_text or
      old.description is distinct from new.description or
      old.image_url is distinct from new.image_url or
      old.starts_at is distinct from new.starts_at or
      old.ends_at is distinct from new.ends_at
    then
      perform public.m4x_enqueue_channel_event(
      'hero',
      'hero:'||to_char(coalesce(new.updated_at,now()),'YYYYMMDDHH24MISSMS'),
        to_jsonb(new)
      );
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_m4x_tg_hero on public.store_hero_settings;
create trigger trg_m4x_tg_hero
after insert or update on public.store_hero_settings
