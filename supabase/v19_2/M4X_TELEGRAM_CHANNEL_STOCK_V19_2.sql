        select decrypted_secret from vault.decrypted_secrets
        where name='m4x_channel_worker_secret_v191'
        order by updated_at desc limit 1
      )
    ),
    body := jsonb_build_object('source','cron','time',now()),
    timeout_milliseconds := 10000
  ) as request_id;
  $$
