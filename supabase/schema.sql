-- M4X STORE V2 - Supabase schema
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique not null,
  icon text,
  description text,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  category_id bigint references public.categories(id) on delete set null,
  name text not null,
  slug text unique not null,
  description text,
  price bigint not null default 0 check (price >= 0),
  old_price bigint,
  cover_url text,
  gallery jsonb not null default '[]'::jsonb,
  delivery_type text not null default 'download' check (delivery_type in ('download','content','license','service','subscription','external')),
  stock_mode text not null default 'unlimited' check (stock_mode in ('unlimited','limited')),
  stock_limit integer check (stock_limit is null or stock_limit >= 0),
  sold_count integer not null default 0 check (sold_count >= 0),
  reserved_count integer not null default 0 check (reserved_count >= 0),
  file_path text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_code text unique not null,
  product_id uuid not null references public.products(id),
  quantity integer not null default 1 check (quantity > 0),
  amount bigint not null check (amount >= 0),
  customer_contact text,
  status text not null default 'pending' check (status in ('pending','paid','expired','cancelled','review')),
  access_token text not null,
  expires_at timestamptz not null,
  paid_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid references public.orders(id),
  transaction_id text unique not null,
  amount bigint not null,
  content text,
  account_number text,
  match_status text not null default 'received' check (match_status in ('received','matched','unmatched','review')),
  raw_data jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.license_keys (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  order_id uuid references public.orders(id),
  license_key text unique not null,
  status text not null default 'available' check (status in ('available','sold','disabled')),
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;

