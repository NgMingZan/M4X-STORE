-- 8) Cron gọi worker mỗi phút. Worker tự quyết định 08:00 / 20:00,
--    xử lý queue sản phẩm/Hero/update và repost X ngày.
do $$
declare r record;
begin
  for r in select jobid from cron.job where jobname='m4x-channel-worker-v19-1' loop
    perform cron.unschedule(r.jobid);
  end loop;
end $$;

select cron.schedule(
  'm4x-channel-worker-v19-1',
  '* * * * *',
  $$
  select net.http_post(
    url := (
      select decrypted_secret from vault.decrypted_secrets
      where name='m4x_channel_project_url_v191'
      order by updated_at desc limit 1
    ) || '/functions/v1/telegram-channel-worker',
    headers := jsonb_build_object(
      'Content-Type','application/json',
      'x-m4x-worker-secret',(
        select decrypted_secret from vault.decrypted_secrets
        where name='m4x_channel_worker_secret_v191'
        order by updated_at desc limit 1
      )
    ),
    body := jsonb_build_object('source','cron','time',now()),
    timeout_milliseconds := 10000
  ) as request_id;
  $$
);

