-- 11B. ADMIN BLOCK / UNBLOCK ACCOUNT
-- ============================================================
create or replace function public.admin_set_user_blocked(
  p_user_id uuid,
  p_blocked boolean,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not public.is_admin() then raise exception 'Không có quyền Admin'; end if;
  if p_user_id=auth.uid() and p_blocked then
    raise exception 'Không thể tự khóa tài khoản Admin đang đăng nhập';
  end if;

  update public.profiles
  set is_blocked=p_blocked,
      blocked_reason=case when p_blocked then nullif(trim(coalesce(p_reason,'')),'') else null end
  where id=p_user_id;

  insert into public.notifications(user_id,title,body,type,reference)
  values(
    p_user_id,
    case when p_blocked then 'Tài khoản bị tạm khóa' else 'Tài khoản đã được mở khóa' end,
    case when p_blocked
      then coalesce(nullif(trim(coalesce(p_reason,'')),''),'Liên hệ Admin để biết thêm chi tiết.')
      else 'Bạn có thể tiếp tục sử dụng M4X STORE.'
    end,
    'system','ACCOUNT'
  );
end;
$$;

revoke all on function public.admin_set_user_blocked(uuid,boolean,text) from public,anon;
grant execute on function public.admin_set_user_blocked(uuid,boolean,text) to authenticated;

