-- 8. CREATE TOPUP - RATE LIMITED
-- ============================================================
create or replace function public.create_wallet_topup(p_amount bigint)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  uid uuid := auth.uid();
  code text;
  exp timestamptz := now() + interval '15 minutes';
begin
  if uid is null then raise exception 'Bạn chưa đăng nhập'; end if;
  if exists(select 1 from public.profiles where id=uid and is_blocked=true) then
    raise exception 'Tài khoản đang bị khóa. Liên hệ Admin.';
  end if;
  perform public.m4x_enforce_rate_limit('create_topup',5,60);

  if p_amount is null or p_amount < 10000 or p_amount > 5000000 then
    raise exception 'Số tiền nạp từ 10.000đ đến 5.000.000đ';
  end if;

  update public.topups set status='expired'
  where user_id=uid and status='pending' and expires_at<now();

  loop
    code := 'NAP' || upper(substr(md5(
      random()::text || clock_timestamp()::text || uid::text
    ),1,10));
    exit when not exists(select 1 from public.topups where topup_code=code);
  end loop;

  insert into public.topups(user_id,topup_code,amount,status,expires_at)
  values(uid,code,p_amount,'pending',exp);

  return jsonb_build_object(
    'topup_code',code,'amount',p_amount,'expires_at',exp
  );
end;
$$;

revoke all on function public.create_wallet_topup(bigint) from public,anon;
grant execute on function public.create_wallet_topup(bigint) to authenticated;

-- ============================================================
-- 9. BUY ONCE / STORE CREDIT
-- ============================================================
create or replace function public.wallet_purchase(
  p_product_id uuid,
  p_quantity integer default 1
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  uid uuid := auth.uid();
  prof public.profiles%rowtype;
  prod public.products%rowtype;
  total bigint;
  av integer;
  code text;
  token text;
  new_balance bigint;
begin
  if uid is null then raise exception 'Bạn chưa đăng nhập'; end if;
  perform public.m4x_enforce_rate_limit('wallet_purchase',8,60);

  if p_quantity is null or p_quantity<>1 then
    raise exception 'Mỗi tài khoản chỉ mua một lần cho mỗi sản phẩm';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(uid::text || ':' || p_product_id::text,0)
  );

  if exists (
    select 1 from public.orders
    where user_id=uid and product_id=p_product_id and status='paid'
  ) then
    raise exception 'Bạn đã mua sản phẩm này';
  end if;

  select * into prof from public.profiles where id=uid for update;
  if not found then raise exception 'Không tìm thấy tài khoản'; end if;
  if prof.is_blocked then
    raise exception 'Tài khoản đang bị khóa. Liên hệ Admin.';
  end if;

  select * into prod
  from public.products
  where id=p_product_id and active=true
  for update;

  if not found then raise exception 'Sản phẩm không tồn tại hoặc đã ẩn'; end if;

  if prod.sale_status='coming_soon' then raise exception 'Sản phẩm sắp ra mắt'; end if;
  if prod.sale_status='discontinued' then raise exception 'Sản phẩm đã ngừng bán'; end if;
  if prod.sale_status='out_of_stock' then raise exception 'Sản phẩm đã hết hàng'; end if;

  if prod.stock_mode='limited' then
    av:=coalesce(prod.stock_limit,0)-prod.sold_count-prod.reserved_count;
    if av<1 then raise exception 'Sản phẩm đã hết hàng'; end if;
  end if;

  total:=prod.price;
  if prof.balance<total then
    raise exception 'Số dư không đủ. Bạn cần nạp thêm %đ', total-prof.balance;
  end if;

  loop
    code:='M4XW'||upper(substr(md5(
      random()::text || clock_timestamp()::text || uid::text
    ),1,10));
    exit when not exists(select 1 from public.orders where order_code=code);
  end loop;

  token:=md5(random()::text||clock_timestamp()::text||uid::text)
       ||md5(random()::text||code);

  update public.profiles
  set balance=balance-total
  where id=uid
  returning balance into new_balance;

  update public.products
  set sold_count=sold_count+1,updated_at=now()
  where id=prod.id;

  insert into public.orders(
    order_code,product_id,quantity,amount,customer_contact,status,
    access_token,expires_at,paid_at,user_id,payment_method,purchased_version
  )
  values(
    code,prod.id,1,total,null,'paid',token,
    now()+interval '10 years',now(),uid,'wallet',prod.version_name
  );

  insert into public.wallet_transactions(
    user_id,amount,type,description,reference
  )
  values(uid,-total,'purchase','Mua '||prod.name,code);

  insert into public.notifications(
    user_id,title,body,type,reference
  )
  values(
    uid,'Mua hàng thành công',
    'Bạn đã sở hữu '||prod.name||'. Có thể tải lại bất cứ lúc nào.',
    'purchase',code
  );

  return jsonb_build_object(
    'order_code',code,
    'access_token',token,
    'amount',total,
    'product_name',prod.name,
    'delivery_type',prod.delivery_type,
    'balance_after',new_balance,
    'version_name',prod.version_name
  );
end;
$$;

revoke all on function public.wallet_purchase(uuid,integer) from public,anon;
grant execute on function public.wallet_purchase(uuid,integer) to authenticated;

-- ============================================================
-- 10. SEPAY WALLET TOPUP
-- ============================================================
create or replace function public.process_wallet_topup(
  p_transaction_id text,
  p_topup_code text,
  p_amount bigint,
  p_content text,
  p_account text,
  p_raw jsonb
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare t public.topups%rowtype;
begin
  if p_transaction_id is null or trim(p_transaction_id)='' then
    raise exception 'Thiếu transaction id';
  end if;

  if exists (
    select 1 from public.topups where bank_transaction_id=p_transaction_id
  ) then
    return jsonb_build_object('result','duplicate');
  end if;

  select * into t from public.topups
  where topup_code=upper(trim(p_topup_code))
  for update;

  if not found then return jsonb_build_object('result','unmatched_topup'); end if;
  if t.status='paid' then return jsonb_build_object('result','already_paid'); end if;

  if t.status<>'pending' or t.expires_at<now() or t.amount<>p_amount then
    update public.topups
    set status='review',bank_transaction_id=p_transaction_id
    where id=t.id;
    return jsonb_build_object('result','review');
  end if;

  update public.profiles set balance=balance+p_amount where id=t.user_id;

  insert into public.wallet_transactions(
    user_id,amount,type,description,reference
  )
  values(t.user_id,p_amount,'topup','Nạp tiền qua ngân hàng',t.topup_code);

  update public.topups
  set status='paid',paid_at=now(),bank_transaction_id=p_transaction_id
  where id=t.id;

  insert into public.notifications(user_id,title,body,type,reference)
  values(
    t.user_id,'Nạp tiền thành công',
    'Đã cộng '||to_char(p_amount,'FM999G999G999')||'đ vào số dư M4X STORE.',
    'topup',t.topup_code
  );

  return jsonb_build_object(
    'result','paid','user_id',t.user_id,'amount',p_amount
  );
end;
$$;

revoke all on function public.process_wallet_topup(
  text,text,bigint,text,text,jsonb
) from public,anon,authenticated;

