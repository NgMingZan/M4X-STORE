-- 11. ADMIN REFUND TO STORE CREDIT
-- ============================================================
create or replace function public.admin_refund_order(
  p_order_id uuid,
  p_reason text default 'Hoàn tiền bởi Admin'
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  o public.orders%rowtype;
  new_balance bigint;
begin
  if not public.is_admin() then raise exception 'Không có quyền Admin'; end if;

  select * into o from public.orders where id=p_order_id for update;
  if not found then raise exception 'Không tìm thấy đơn hàng'; end if;
  if o.status='refunded' then raise exception 'Đơn này đã được hoàn tiền'; end if;
  if o.status<>'paid' then raise exception 'Chỉ hoàn tiền cho đơn đã thanh toán'; end if;
  if o.user_id is null then
    raise exception 'Đơn không gắn với tài khoản, không thể hoàn vào số dư';
  end if;

  update public.profiles
  set balance=balance+o.amount
  where id=o.user_id
  returning balance into new_balance;

  insert into public.wallet_transactions(
    user_id,amount,type,description,reference
  )
  values(
    o.user_id,o.amount,'refund',
    coalesce(nullif(trim(p_reason),''),'Hoàn tiền bởi Admin'),
    o.order_code
  );

  update public.orders
  set status='refunded',refunded_at=now(),refund_reason=p_reason
  where id=o.id;

  update public.products
  set sold_count=greatest(0,sold_count-o.quantity),updated_at=now()
  where id=o.product_id;

  insert into public.notifications(user_id,title,body,type,reference)
  values(
    o.user_id,'Đã hoàn tiền',
    'Đơn '||o.order_code||' đã được hoàn '||
    to_char(o.amount,'FM999G999G999')||'đ vào số dư.',
    'refund',o.order_code
  );

  return jsonb_build_object(
    'order_code',o.order_code,
    'refund_amount',o.amount,
    'balance_after',new_balance
  );
end;
$$;

revoke all on function public.admin_refund_order(uuid,text) from public,anon;
grant execute on function public.admin_refund_order(uuid,text) to authenticated;


