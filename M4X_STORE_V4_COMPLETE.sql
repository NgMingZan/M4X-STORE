-- ============================================================
-- 5. INTERNAL RATE LIMIT
-- ============================================================
create or replace function public.m4x_enforce_rate_limit(
  p_action text,
  p_max_hits integer,
  p_window_seconds integer
)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  uid uuid := auth.uid();
  hits integer;
begin
  if uid is null then raise exception 'Bạn chưa đăng nhập'; end if;

  delete from public.rate_events
  where created_at < now() - interval '1 day';

  select count(*) into hits
  from public.rate_events
  where user_id=uid
    and action=p_action
    and created_at > now() - make_interval(secs => p_window_seconds);

  if hits >= p_max_hits then
    raise exception 'Thao tác quá nhanh. Vui lòng thử lại sau.';
  end if;

  insert into public.rate_events(user_id,action) values(uid,p_action);
end;
$$;

revoke all on function public.m4x_enforce_rate_limit(text,integer,integer)
from public,anon,authenticated;

