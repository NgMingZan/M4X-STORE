-- 12. ADMIN PUBLISH PRODUCT UPDATE + NOTIFY OWNERS
-- ============================================================
create or replace function public.admin_publish_product_update(
  p_product_id uuid,
  p_version_name text,
  p_changelog text
)
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not public.is_admin() then raise exception 'Không có quyền Admin'; end if;

  update public.products
  set version_name=trim(p_version_name),
      changelog=p_changelog,
      updated_at=now()
  where id=p_product_id;

  insert into public.product_updates(product_id,version_name,changelog)
  values(p_product_id,trim(p_version_name),p_changelog)
  on conflict(product_id,version_name)
  do update set changelog=excluded.changelog,created_at=now();

  insert into public.notifications(user_id,title,body,type,reference)
  select distinct
    o.user_id,
    'Sản phẩm có bản cập nhật',
    p.name||' đã cập nhật lên phiên bản '||trim(p_version_name)||
      coalesce(E'\n'||nullif(trim(p_changelog),''),''),
    'update',
    p_product_id::text
  from public.orders o
  join public.products p on p.id=o.product_id
  where o.product_id=p_product_id
    and o.status='paid'
    and o.user_id is not null;
end;
$$;

